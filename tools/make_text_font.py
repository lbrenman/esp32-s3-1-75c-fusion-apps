#!/usr/bin/env python3
"""
make_text_font.py - accented Latin letters for the built-in Montserrat fonts (LVGL 9).

    python3 tools/make_text_font.py assets/Montserrat-Medium.ttf main/ui

LVGL's built-in Montserrat fonts only have ASCII, so "Adiós" or "Grüße" can't be drawn with them.
This writes ui_font_latin_<size>.c for each size in SIZES: just the extra glyphs (Latin-1,
Latin Extended-A, curly quotes, dashes, the euro sign...), with .fallback pointing at the
built-in lv_font_montserrat_<size>. Labels use ui_font_latin_<size>; ASCII text then still comes
from the built-in font (same look, same kerning) and only the accented letters come from here.
Also writes ui_fonts.h.

Same layout as lv_font_conv output: 4 bpp, uncompressed, sparse character map.
Needs Pillow (its FreeType renderer); fontTools (optional) skips code points the font lacks.
Montserrat-Medium.ttf is the same file LVGL's built-in fonts are made from
(lvgl/scripts/built_in_font), SIL Open Font License 1.1.
"""
import sys, os
from PIL import ImageFont, Image, ImageDraw

SIZES = [14, 16, 20, 28]

# U+00A0..U+017F: Latin-1 Supplement + Latin Extended-A (Spanish, French, German, Portuguese,
# Italian, Dutch, plus Polish, Czech, Turkish... for names). Then common punctuation.
RANGES = [(0x00A0, 0x017F), (0x0400, 0x045F)]   # + Cyrillic (Russian)
EXTRA = [0x0218, 0x0219, 0x021A, 0x021B,                  # Romanian S/T with comma
         0x2013, 0x2014, 0x2018, 0x2019, 0x201A, 0x201C, 0x201D, 0x201E,
         0x2022, 0x2026, 0x2039, 0x203A, 0x20AC]
ASCII = [chr(c) for c in range(0x21, 0x7F)]


def code_points(ttf):
    cps = [cp for a, b in RANGES for cp in range(a, b + 1)] + EXTRA
    try:
        from fontTools.ttLib import TTFont
        cmap = TTFont(ttf).getBestCmap()
        cps = [cp for cp in cps if cp in cmap]
    except ImportError:
        pass
    return sorted(set(cps))


def build(ttf, size, out_dir, cps):
    font = ImageFont.truetype(ttf, size)
    ascent, _ = font.getmetrics()
    bitmap, glyphs = [], []
    top, bottom = 0, 0           # highest / lowest pixel over ASCII and these glyphs (from the baseline)
    for ch in ASCII:
        l, t, r, b = font.getbbox(ch)
        top, bottom = max(top, ascent - t), min(bottom, ascent - b)
    for cp in cps:
        ch = chr(cp)
        l, t, r, b = font.getbbox(ch)
        w, h = max(r - l, 0), max(b - t, 0)
        if w == 0 or h == 0:     # spaces
            w = h = 0
        else:
            top, bottom = max(top, ascent - t), min(bottom, ascent - b)
        start = len(bitmap)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255)
            px = list(img.get_flattened_data()) if hasattr(img, "get_flattened_data") else list(img.getdata())
            nib = [p >> 4 for p in px]
            if len(nib) % 2:
                nib.append(0)
            for i in range(0, len(nib), 2):
                bitmap.append((nib[i] << 4) | nib[i + 1])
        adv = int(round(font.getlength(ch) * 16))
        glyphs.append((start, min(adv, 4095), w, h, l if w else 0, (ascent - b) if w else 0))

    name = "ui_font_latin_%d" % size
    L = []
    a = L.append
    a("/* %s: %d px, 4 bpp. Accented Latin letters and punctuation for the built-in" % (name, size))
    a(" * lv_font_montserrat_%d (its fallback, which draws ASCII). Generated by tools/make_text_font.py" % size)
    a(" * from Montserrat Medium (SIL Open Font License 1.1). Do not edit. */")
    a('#include "lvgl.h"\n')
    a("#if !LV_FONT_MONTSERRAT_%d" % size)
    a("#error \"%s needs LV_FONT_MONTSERRAT_%d (CONFIG_LV_FONT_MONTSERRAT_%d=y)\"" % (name, size, size))
    a("#endif\n")
    a("static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {")
    for i in range(0, len(bitmap), 16):
        a("    " + ", ".join("0x%02x" % v for v in bitmap[i:i + 16]) + ",")
    if not bitmap:
        a("    0x00,")
    a("};\n")
    a("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {")
    a("    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id = 0 reserved */,")
    for (bi, adv, w, h, ox, oy), cp in zip(glyphs, cps):
        a("    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d}, /* U+%04X */"
          % (bi, adv, w, h, ox, oy, cp))
    a("};\n")
    first = cps[0]
    a("static const uint16_t unicode_list_0[] = {")
    offs = ["0x%x" % (cp - first) for cp in cps]
    for i in range(0, len(offs), 12):
        a("    " + ", ".join(offs[i:i + 12]) + ",")
    a("};\n")
    a("static const lv_font_fmt_txt_cmap_t cmaps[] = {")
    a("    {")
    a("        .range_start = %d, .range_length = %d, .glyph_id_start = 1," % (first, cps[-1] - first + 1))
    a("        .unicode_list = unicode_list_0, .glyph_id_ofs_list = NULL, .list_length = %d, "
      ".type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY" % len(cps))
    a("    }")
    a("};\n")
    a("static const lv_font_fmt_txt_dsc_t font_dsc = {")
    a("    .glyph_bitmap = glyph_bitmap,")
    a("    .glyph_dsc = glyph_dsc,")
    a("    .cmaps = cmaps,")
    a("    .kern_dsc = NULL,")
    a("    .kern_scale = 0,")
    a("    .cmap_num = 1,")
    a("    .bpp = 4,")
    a("    .kern_classes = 0,")
    a("    .bitmap_format = 0,")
    a("};\n")
    a("/* line height covers accented capitals (taller than the built-in font's ASCII-only line) */")
    a("const lv_font_t %s = {" % name)
    a("    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,")
    a("    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,")
    a("    .line_height = %d," % (top - bottom))
    a("    .base_line = %d," % (-bottom))
    a("    .subpx = LV_FONT_SUBPX_NONE,")
    a("    .underline_position = -1,")
    a("    .underline_thickness = 1,")
    a("    .dsc = &font_dsc,")
    a("    .fallback = &lv_font_montserrat_%d," % size)
    a("};")
    with open(os.path.join(out_dir, name + ".c"), "w") as f:
        f.write("\n".join(L) + "\n")
    return name


def main():
    ttf, out_dir = sys.argv[1], sys.argv[2]
    cps = code_points(ttf)
    names = [build(ttf, s, out_dir, cps) for s in SIZES]
    h = ["#pragma once",
         "/* Text fonts with accented Latin letters, generated by tools/make_text_font.py.",
         " * Each one draws U+00A0..U+017F, Cyrillic (and curly quotes, dashes, euro) itself and falls back to the",
         " * built-in lv_font_montserrat_<size> for ASCII. Use with text_to_intl() (text_ascii.h). */",
         '#include "lvgl.h"', ""]
    h += ["LV_FONT_DECLARE(%s)" % n for n in names]
    h += ["", "/* Arabic and Devanagari, from tools/make_script_fonts.py (they fall back to the fonts above) */",
          '#include "ui_fonts_intl.h"']
    with open(os.path.join(out_dir, "ui_fonts.h"), "w") as f:
        f.write("\n".join(h) + "\n")
    print("Wrote %s (%d glyphs each)" % (", ".join(n + ".c" for n in names), len(cps)))


if __name__ == "__main__":
    main()
