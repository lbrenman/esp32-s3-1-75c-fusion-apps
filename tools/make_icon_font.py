#!/usr/bin/env python3
"""
make_icon_font.py - turn a few Font Awesome glyphs into LVGL 9 font C files.

    python3 tools/make_icon_font.py <fa-solid-900.ttf> <out_dir>

Writes ui_icons_<size>.c for each size in SIZES plus ui_icons.h (UTF-8 string macros).
Same layout as lv_font_conv output: 4 bpp, uncompressed, sparse character map.
Needs only Pillow (its FreeType renderer).
"""
import sys, os
from PIL import ImageFont, Image, ImageDraw

SIZES = [16, 20, 28, 56]

# name -> Font Awesome 6 Free Solid codepoint
ICONS = [
    ("MIC", 0xF130), ("MIC_LINES", 0xF3C9), ("GEAR", 0xF013), ("SLIDERS", 0xF1DE),
    ("WIFI", 0xF1EB), ("SUN", 0xF185), ("MOON", 0xF186), ("HALF", 0xF042),
    ("KEY", 0xF084), ("LINK", 0xF0C1), ("SERVER", 0xF233), ("HOUSE", 0xF015),
    ("LEFT", 0xF053), ("RIGHT", 0xF054), ("UP", 0xF077), ("DOWN", 0xF078),
    ("EYE", 0xF06E), ("EYE_SLASH", 0xF070), ("LOCK", 0xF023), ("CHECK", 0xF00C),
    ("XMARK", 0xF00D), ("VOLUME", 0xF028), ("INFO", 0xF05A), ("ROTATE", 0xF021),
    ("COMMENT", 0xF4AD), ("WARN", 0xF071), ("POWER", 0xF011), ("RESET", 0xF0E2),
    ("PLUG", 0xF1E6), ("GLOBE", 0xF0AC), ("BRIGHT", 0xF0EB), ("PEN", 0xF304),
    ("SIGNAL", 0xF012), ("WAVE", 0xF83E), ("HAND", 0xF256), ("ROBOT", 0xF544),
    ("CHART", 0xF201), ("PLUS", 0x2B), ("PAUSE", 0xF04C), ("PLAY", 0xF04B),
    ("LIST", 0xF03A), ("TRASH", 0xF1F8),
    ("BATTERY_FULL", 0xF240), ("BATTERY_3Q", 0xF241), ("BATTERY_HALF", 0xF242),
    ("BATTERY_1Q", 0xF243), ("BATTERY_EMPTY", 0xF244), ("BOLT", 0xF0E7),
    ("LANGUAGE", 0xF1AB), ("SWAP", 0xF0EC), ("ARROW_RIGHT", 0xF061),
]


def utf8_escape(cp):
    return "".join("\\x%02X" % b for b in chr(cp).encode("utf-8"))


def build(ttf, size, out_dir):
    font = ImageFont.truetype(ttf, size)
    ascent, descent = font.getmetrics()
    cps = sorted(cp for _, cp in ICONS)
    bitmap = []           # bytes
    glyphs = []           # (bitmap_index, adv_w16, w, h, ofs_x, ofs_y)
    for cp in cps:
        ch = chr(cp)
        l, t, r, b = font.getbbox(ch)
        w, h = max(r - l, 0), max(b - t, 0)
        img = Image.new("L", (max(w, 1), max(h, 1)), 0)
        ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255)
        px = list(img.get_flattened_data()) if hasattr(img, "get_flattened_data") else list(img.getdata())
        start = len(bitmap)
        nib = [p >> 4 for p in px[: w * h]]
        if len(nib) % 2:
            nib.append(0)
        for i in range(0, len(nib), 2):
            bitmap.append((nib[i] << 4) | nib[i + 1])
        adv = int(round(font.getlength(ch) * 16))
        glyphs.append((start, min(adv, 4095), w, h, l, ascent - b))

    name = "ui_icons_%d" % size
    lines = []
    a = lines.append
    a("/* %s: %d px, 4 bpp icon font generated by tools/make_icon_font.py" % (name, size))
    a(" * from Font Awesome Free 6 Solid (https://fontawesome.com, icons CC BY 4.0, font SIL OFL 1.1). */")
    a('#include "lvgl.h"\n')
    a("static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {")
    for i in range(0, len(bitmap), 16):
        a("    " + ", ".join("0x%02x" % v for v in bitmap[i:i + 16]) + ",")
    a("};\n")
    a("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {")
    a("    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id = 0 reserved */,")
    for (bi, adv, w, h, ox, oy), cp in zip(glyphs, cps):
        a("    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d}, /* U+%04X */"
          % (bi, adv, w, h, ox, oy, cp))
    a("};\n")
    first = cps[0]
    a("static const uint16_t unicode_list_0[] = {")
    a("    " + ", ".join("0x%x" % (cp - first) for cp in cps))
    a("};\n")
    a("static const lv_font_fmt_txt_cmap_t cmaps[] = {")
    a("    {")
    a("        .range_start = %d, .range_length = %d, .glyph_id_start = 1," % (first, cps[-1] - first + 1))
    a("        .unicode_list = unicode_list_0, .glyph_id_ofs_list = NULL, .list_length = %d, "
      ".type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY" % len(cps))
    a("    }")
    a("};\n")
    a("static const lv_font_fmt_txt_dsc_t font_dsc = {")
    a("    .glyph_bitmap = glyph_bitmap,")
    a("    .glyph_dsc = glyph_dsc,")
    a("    .cmaps = cmaps,")
    a("    .kern_dsc = NULL,")
    a("    .kern_scale = 0,")
    a("    .cmap_num = 1,")
    a("    .bpp = 4,")
    a("    .kern_classes = 0,")
    a("    .bitmap_format = 0,")
    a("};\n")
    a("const lv_font_t %s = {" % name)
    a("    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,")
    a("    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,")
    a("    .line_height = %d," % (ascent + descent))
    a("    .base_line = %d," % descent)
    a("    .subpx = LV_FONT_SUBPX_NONE,")
    a("    .underline_position = -1,")
    a("    .underline_thickness = 1,")
    a("    .dsc = &font_dsc,")
    a("    .fallback = NULL,")
    a("};")
    with open(os.path.join(out_dir, name + ".c"), "w") as f:
        f.write("\n".join(lines) + "\n")
    return name


def main():
    ttf, out_dir = sys.argv[1], sys.argv[2]
    names = [build(ttf, s, out_dir) for s in SIZES]
    h = ["#pragma once", "/* Icon fonts generated by tools/make_icon_font.py (Font Awesome Free 6 Solid). */",
         '#include "lvgl.h"', ""]
    h += ["LV_FONT_DECLARE(%s)" % n for n in names]
    h.append("")
    for n, cp in ICONS:
        h.append('#define ICON_%-10s "%s"   /* U+%04X */' % (n, utf8_escape(cp), cp))
    with open(os.path.join(out_dir, "ui_icons.h"), "w") as f:
        f.write("\n".join(h) + "\n")


if __name__ == "__main__":
    main()
